\set ON_ERROR_STOP on
\encoding UTF8

DROP DATABASE IF EXISTS ais_agency_employment WITH (FORCE);
CREATE DATABASE ais_agency_employment
    WITH ENCODING 'UTF8'
         TEMPLATE template0;

\connect ais_agency_employment

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =============================================================================
--  1. ТАБЛИЦА АВТОРИЗАЦИИ И РОЛИ ПОЛЬЗОВАТЕЛЕЙ
-- =============================================================================

CREATE TABLE roles (
    role_id      integer      GENERATED BY DEFAULT AS IDENTITY,
    code         varchar(30)  NOT NULL,
    name         varchar(100) NOT NULL,
    description  text,
    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_code UNIQUE (code),
    CONSTRAINT uq_roles_name UNIQUE (name),
    CONSTRAINT chk_roles_code CHECK (code ~ '^[a-z_]+$')
);

COMMENT ON TABLE  roles IS 'Роли пользователей системы (соискатель, агент, администратор)';
COMMENT ON COLUMN roles.code IS 'Машинный код роли';
COMMENT ON COLUMN roles.name IS 'Наименование роли';

CREATE TABLE users (
    user_id        integer      GENERATED BY DEFAULT AS IDENTITY,
    role_id        integer      NOT NULL,
    login          varchar(50)  NOT NULL,
    password_hash  text         NOT NULL,
    email          varchar(254) NOT NULL,
    phone          varchar(20),
    is_active      boolean      NOT NULL DEFAULT true,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now(),
    last_login_at  timestamptz,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id)
        REFERENCES roles (role_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_users_login UNIQUE (login),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_login CHECK (login ~ '^[A-Za-z0-9_.-]{3,50}$'),
    CONSTRAINT chk_users_password_hash CHECK (length(password_hash) >= 20),
    CONSTRAINT chk_users_email CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

COMMENT ON TABLE  users IS 'Учётные записи пользователей (таблица авторизации)';
COMMENT ON COLUMN users.password_hash IS 'Хеш пароля, сформированный функцией crypt() расширения pgcrypto';
COMMENT ON COLUMN users.is_active IS 'Признак активной учётной записи';
COMMENT ON COLUMN users.last_login_at IS 'Дата и время последнего входа в систему';

-- =============================================================================
--  2. СПРАВОЧНИКИ
-- =============================================================================

CREATE TABLE employment_statuses (
    employment_status_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    code                  varchar(30)  NOT NULL,
    name                  varchar(100) NOT NULL,
    description           text,
    CONSTRAINT pk_employment_statuses PRIMARY KEY (employment_status_id),
    CONSTRAINT uq_employment_statuses_code UNIQUE (code),
    CONSTRAINT uq_employment_statuses_name UNIQUE (name)
);

COMMENT ON TABLE employment_statuses IS 'Справочник статусов трудоустройства соискателя';

CREATE TABLE employment_types (
    employment_type_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    code                varchar(30)  NOT NULL,
    name                varchar(100) NOT NULL,
    description         text,
    CONSTRAINT pk_employment_types PRIMARY KEY (employment_type_id),
    CONSTRAINT uq_employment_types_code UNIQUE (code),
    CONSTRAINT uq_employment_types_name UNIQUE (name)
);

COMMENT ON TABLE employment_types IS 'Справочник типов занятости по вакансии';

CREATE TABLE vacancy_statuses (
    vacancy_status_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    code               varchar(30)  NOT NULL,
    name               varchar(100) NOT NULL,
    description        text,
    CONSTRAINT pk_vacancy_statuses PRIMARY KEY (vacancy_status_id),
    CONSTRAINT uq_vacancy_statuses_code UNIQUE (code),
    CONSTRAINT uq_vacancy_statuses_name UNIQUE (name)
);

COMMENT ON TABLE vacancy_statuses IS 'Справочник статусов вакансии';

CREATE TABLE application_statuses (
    application_status_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    code                   varchar(30)  NOT NULL,
    name                   varchar(100) NOT NULL,
    description            text,
    CONSTRAINT pk_application_statuses PRIMARY KEY (application_status_id),
    CONSTRAINT uq_application_statuses_code UNIQUE (code),
    CONSTRAINT uq_application_statuses_name UNIQUE (name)
);

COMMENT ON TABLE application_statuses IS 'Справочник статусов заявки на трудоустройство';

CREATE TABLE deal_statuses (
    deal_status_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    code            varchar(30)  NOT NULL,
    name            varchar(100) NOT NULL,
    description     text,
    CONSTRAINT pk_deal_statuses PRIMARY KEY (deal_status_id),
    CONSTRAINT uq_deal_statuses_code UNIQUE (code),
    CONSTRAINT uq_deal_statuses_name UNIQUE (name)
);

COMMENT ON TABLE deal_statuses IS 'Справочник статусов сделки по трудоустройству';

-- =============================================================================
--  3. СОИСКАТЕЛИ, РЕЗЮМЕ И ОПЫТ РАБОТЫ
-- =============================================================================

CREATE TABLE job_seekers (
    job_seeker_id         integer      GENERATED BY DEFAULT AS IDENTITY,
    user_id               integer      NOT NULL,
    last_name             varchar(60)  NOT NULL,
    first_name            varchar(60)  NOT NULL,
    middle_name           varchar(60),
    birth_date            date,
    qualification         text,
    photo_path            varchar(255),
    employment_status_id  integer      NOT NULL,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_job_seekers PRIMARY KEY (job_seeker_id),
    CONSTRAINT fk_job_seekers_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_job_seekers_status FOREIGN KEY (employment_status_id)
        REFERENCES employment_statuses (employment_status_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_job_seekers_user UNIQUE (user_id),
    CONSTRAINT chk_job_seekers_birth_date CHECK (birth_date >= DATE '1900-01-01')
);

COMMENT ON TABLE  job_seekers IS 'Профили соискателей';
COMMENT ON COLUMN job_seekers.photo_path IS 'Путь к файлу фотографии в хранилище';
COMMENT ON COLUMN job_seekers.qualification IS 'Квалификация и краткая профессиональная характеристика';

CREATE TABLE resumes (
    resume_id        integer       GENERATED BY DEFAULT AS IDENTITY,
    job_seeker_id    integer       NOT NULL,
    desired_position varchar(200)  NOT NULL,
    desired_salary   numeric(12,2),
    education        text,
    skills           text,
    about            text,
    attachment_path  varchar(255),
    is_active        boolean       NOT NULL DEFAULT true,
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_resumes PRIMARY KEY (resume_id),
    CONSTRAINT fk_resumes_job_seeker FOREIGN KEY (job_seeker_id)
        REFERENCES job_seekers (job_seeker_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT chk_resumes_desired_salary CHECK (desired_salary IS NULL OR desired_salary >= 0)
);

COMMENT ON TABLE  resumes IS 'Резюме соискателей';
COMMENT ON COLUMN resumes.attachment_path IS 'Путь к вложенному файлу резюме';
COMMENT ON COLUMN resumes.is_active IS 'Признак актуальности резюме';

CREATE TABLE work_experiences (
    work_experience_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    resume_id           integer      NOT NULL,
    organization        varchar(200) NOT NULL,
    position            varchar(150) NOT NULL,
    start_date          date         NOT NULL,
    end_date            date,
    responsibilities    text,
    CONSTRAINT pk_work_experiences PRIMARY KEY (work_experience_id),
    CONSTRAINT fk_work_experiences_resume FOREIGN KEY (resume_id)
        REFERENCES resumes (resume_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT chk_work_experiences_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

COMMENT ON TABLE work_experiences IS 'Сведения о предыдущих местах работы соискателя';

-- =============================================================================
--  4. РАБОТОДАТЕЛИ И ВАКАНСИИ
-- =============================================================================

CREATE TABLE employers (
    employer_id     integer      GENERATED BY DEFAULT AS IDENTITY,
    company_name    varchar(200) NOT NULL,
    inn             varchar(12),
    contact_person  varchar(150) NOT NULL,
    phone           varchar(20)  NOT NULL,
    email           varchar(254) NOT NULL,
    address         varchar(300),
    website         varchar(200),
    description     text,
    logo_path       varchar(255),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_employers PRIMARY KEY (employer_id),
    CONSTRAINT uq_employers_inn UNIQUE (inn),
    CONSTRAINT chk_employers_inn CHECK (inn IS NULL OR inn ~ '^([0-9]{10}|[0-9]{12})$'),
    CONSTRAINT chk_employers_email CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

COMMENT ON TABLE  employers IS 'Организации-работодатели';
COMMENT ON COLUMN employers.inn IS 'ИНН организации (10 или 12 цифр)';
COMMENT ON COLUMN employers.logo_path IS 'Путь к файлу логотипа организации';

CREATE TABLE vacancies (
    vacancy_id          integer       GENERATED BY DEFAULT AS IDENTITY,
    employer_id         integer       NOT NULL,
    employment_type_id  integer       NOT NULL,
    vacancy_status_id   integer       NOT NULL,
    title               varchar(200)  NOT NULL,
    salary_from         numeric(12,2),
    salary_to           numeric(12,2),
    responsibilities    text          NOT NULL,
    requirements        text,
    published_at        timestamptz,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_vacancies PRIMARY KEY (vacancy_id),
    CONSTRAINT fk_vacancies_employer FOREIGN KEY (employer_id)
        REFERENCES employers (employer_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_vacancies_employment_type FOREIGN KEY (employment_type_id)
        REFERENCES employment_types (employment_type_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_vacancies_status FOREIGN KEY (vacancy_status_id)
        REFERENCES vacancy_statuses (vacancy_status_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_vacancies_salary_from CHECK (salary_from IS NULL OR salary_from >= 0),
    CONSTRAINT chk_vacancies_salary_to CHECK (salary_to IS NULL OR salary_to >= 0),
    CONSTRAINT chk_vacancies_salary_range CHECK (
        salary_from IS NULL OR salary_to IS NULL OR salary_to >= salary_from
    )
);

COMMENT ON TABLE  vacancies IS 'Вакансии работодателей';
COMMENT ON COLUMN vacancies.title IS 'Наименование должности';
COMMENT ON COLUMN vacancies.published_at IS 'Дата и время публикации вакансии';

-- =============================================================================
--  5. ЗАЯВКИ, СДЕЛКИ И ТРУДОВЫЕ ДОГОВОРЫ
-- =============================================================================

CREATE TABLE applications (
    application_id         integer      GENERATED BY DEFAULT AS IDENTITY,
    resume_id              integer      NOT NULL,
    vacancy_id             integer      NOT NULL,
    application_status_id  integer      NOT NULL,
    cover_letter           text,
    created_at             timestamptz  NOT NULL DEFAULT now(),
    updated_at             timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_applications PRIMARY KEY (application_id),
    CONSTRAINT fk_applications_resume FOREIGN KEY (resume_id)
        REFERENCES resumes (resume_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_applications_vacancy FOREIGN KEY (vacancy_id)
        REFERENCES vacancies (vacancy_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_applications_status FOREIGN KEY (application_status_id)
        REFERENCES application_statuses (application_status_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_applications_resume_vacancy UNIQUE (resume_id, vacancy_id)
);

COMMENT ON TABLE applications IS 'Заявки соискателей на вакансии';
COMMENT ON COLUMN applications.cover_letter IS 'Сопроводительное письмо соискателя';

CREATE TABLE agents (
    agent_id     integer      GENERATED BY DEFAULT AS IDENTITY,
    user_id      integer      NOT NULL,
    last_name    varchar(60)  NOT NULL,
    first_name   varchar(60)  NOT NULL,
    middle_name  varchar(60),
    position     varchar(100) NOT NULL DEFAULT 'Агент по трудоустройству',
    phone        varchar(20),
    hired_at     date         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_agents PRIMARY KEY (agent_id),
    CONSTRAINT fk_agents_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT uq_agents_user UNIQUE (user_id)
);

COMMENT ON TABLE agents IS 'Агенты по трудоустройству — сотрудники агентства';

CREATE TABLE deals (
    deal_id             integer       GENERATED BY DEFAULT AS IDENTITY,
    application_id      integer       NOT NULL,
    agent_id            integer       NOT NULL,
    deal_status_id      integer       NOT NULL,
    deal_date           date          NOT NULL DEFAULT CURRENT_DATE,
    amount              numeric(12,2) NOT NULL DEFAULT 0,
    terms               text,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_deals PRIMARY KEY (deal_id),
    CONSTRAINT fk_deals_application FOREIGN KEY (application_id)
        REFERENCES applications (application_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_deals_agent FOREIGN KEY (agent_id)
        REFERENCES agents (agent_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_deals_status FOREIGN KEY (deal_status_id)
        REFERENCES deal_statuses (deal_status_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_deals_application UNIQUE (application_id),
    CONSTRAINT chk_deals_amount CHECK (amount >= 0)
);

COMMENT ON TABLE  deals IS 'Сделки по трудоустройству, оформленные по заявкам';
COMMENT ON COLUMN deals.amount IS 'Стоимость услуг агентства по сделке, руб.';

CREATE TABLE contracts (
    contract_id      integer       GENERATED BY DEFAULT AS IDENTITY,
    deal_id          integer       NOT NULL,
    agent_id         integer       NOT NULL,
    contract_number  varchar(30)   NOT NULL,
    signed_at        date          NOT NULL,
    start_date       date          NOT NULL,
    end_date         date,
    salary           numeric(12,2),
    terms            text,
    file_path        varchar(255),
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_contracts PRIMARY KEY (contract_id),
    CONSTRAINT fk_contracts_deal FOREIGN KEY (deal_id)
        REFERENCES deals (deal_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_contracts_agent FOREIGN KEY (agent_id)
        REFERENCES agents (agent_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_contracts_deal UNIQUE (deal_id),
    CONSTRAINT uq_contracts_number UNIQUE (contract_number),
    CONSTRAINT chk_contracts_salary CHECK (salary IS NULL OR salary >= 0),
    CONSTRAINT chk_contracts_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

COMMENT ON TABLE  contracts IS 'Трудовые договоры, оформленные по сделкам';
COMMENT ON COLUMN contracts.contract_number IS 'Номер трудового договора';
COMMENT ON COLUMN contracts.file_path IS 'Путь к файлу договора в хранилище';
COMMENT ON COLUMN contracts.end_date IS 'Дата окончания договора; NULL — бессрочный договор';

