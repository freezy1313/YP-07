CREATE VIEW v_users AS
SELECT u.user_id,
       u.last_name || ' ' || u.first_name ||
           COALESCE(' ' || u.middle_name, '') AS full_name,
       r.name AS role,
       a.login,
       u.email,
       u.phone,
       u.has_medical_book
FROM users u
JOIN roles r ON r.role_id = u.role_id
JOIN authorizations a ON a.authorization_id = u.authorization_id;

COMMENT ON VIEW v_users IS 'Пользователи с ролью и логином';

CREATE VIEW v_resumes AS
SELECT res.resume_id,
       res.user_id,
       u.last_name || ' ' || u.first_name ||
           COALESCE(' ' || u.middle_name, '') AS applicant,
       dp.specialization AS desired_position,
       res.experience,
       rs.name AS status,
       res.personal_data_consent,
       res.published_at
FROM resumes res
JOIN users u ON u.user_id = res.user_id
JOIN desired_positions dp ON dp.desired_position_id = res.desired_position_id
JOIN resume_statuses rs ON rs.resume_status_id = res.resume_status_id;

COMMENT ON VIEW v_resumes IS 'Резюме с ФИО соискателя, должностью и статусом';

CREATE VIEW v_vacancies AS
SELECT v.vacancy_id,
       v.user_id AS employer_id,
       u.last_name || ' ' || u.first_name ||
           COALESCE(' ' || u.middle_name, '') AS employer,
       pt.name AS position_title,
       v.salary,
       et.name AS employment_type,
       wm.name AS work_mode,
       v.opened_at,
       v.closed_at,
       CASE WHEN v.closed_at IS NULL THEN 'Открыта' ELSE 'Закрыта' END AS status
FROM vacancies v
JOIN users u ON u.user_id = v.user_id
JOIN position_titles pt ON pt.position_title_id = v.position_title_id
JOIN employment_types et ON et.employment_type_id = v.employment_type_id
JOIN work_modes wm ON wm.work_mode_id = v.work_mode_id;

COMMENT ON VIEW v_vacancies IS 'Вакансии с работодателем, условиями и статусом';

CREATE VIEW v_applications AS
SELECT a.application_id,
       a.resume_id,
       u.last_name || ' ' || u.first_name ||
           COALESCE(' ' || u.middle_name, '') AS applicant,
       a.vacancy_id,
       pt.name AS position_title,
       emp.last_name || ' ' || emp.first_name ||
           COALESCE(' ' || emp.middle_name, '') AS employer,
       a.response_date,
       ast.name AS status
FROM applications a
JOIN resumes res ON res.resume_id = a.resume_id
JOIN users u ON u.user_id = res.user_id
JOIN vacancies v ON v.vacancy_id = a.vacancy_id
JOIN users emp ON emp.user_id = v.user_id
