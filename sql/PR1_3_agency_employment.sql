CREATE VIEW v_open_vacancies AS
SELECT v.vacancy_id,
       v.title                AS position,
       e.company_name         AS employer,
       et.name                AS employment_type,
       v.salary_from,
       v.salary_to,
       v.published_at,
       v.requirements
FROM vacancies v
JOIN employers e        ON e.employer_id = v.employer_id
JOIN employment_types et ON et.employment_type_id = v.employment_type_id
JOIN vacancy_statuses vs ON vs.vacancy_status_id = v.vacancy_status_id
WHERE vs.code = 'open';

COMMENT ON VIEW v_open_vacancies IS 'Открытые вакансии с работодателем и типом занятости';

CREATE VIEW v_resume_profiles AS
SELECT r.resume_id,
       js.job_seeker_id,
       js.last_name || ' ' || js.first_name || COALESCE(' ' || js.middle_name, '') AS full_name,
       r.desired_position,
       r.desired_salary,
       es.name                AS employment_status,
       r.is_active,
       count(we.work_experience_id) AS experience_count
FROM resumes r
JOIN job_seekers js          ON js.job_seeker_id = r.job_seeker_id
JOIN employment_statuses es  ON es.employment_status_id = js.employment_status_id
LEFT JOIN work_experiences we ON we.resume_id = r.resume_id
GROUP BY r.resume_id, js.job_seeker_id, js.last_name, js.first_name, js.middle_name,
         r.desired_position, r.desired_salary, es.name, r.is_active;

COMMENT ON VIEW v_resume_profiles IS 'Резюме соискателей с ФИО, статусом трудоустройства и числом мест работы';

CREATE VIEW v_applications_details AS
SELECT a.application_id,
       js.last_name || ' ' || js.first_name || COALESCE(' ' || js.middle_name, '') AS job_seeker,
       r.desired_position,
       v.title                AS vacancy,
       e.company_name         AS employer,
       aps.name               AS application_status,
       a.created_at,
       a.cover_letter
FROM applications a
JOIN resumes r               ON r.resume_id = a.resume_id
JOIN job_seekers js          ON js.job_seeker_id = r.job_seeker_id
JOIN vacancies v             ON v.vacancy_id = a.vacancy_id
JOIN employers e             ON e.employer_id = v.employer_id
JOIN application_statuses aps ON aps.application_status_id = a.application_status_id;

COMMENT ON VIEW v_applications_details IS 'Заявки с данными соискателя, вакансии и статуса';

CREATE VIEW v_deals_details AS
SELECT d.deal_id,
       d.deal_date,
       ds.name                AS deal_status,
       d.amount,
       ag.last_name || ' ' || ag.first_name || COALESCE(' ' || ag.middle_name, '') AS agent,
       js.last_name || ' ' || js.first_name || COALESCE(' ' || js.middle_name, '') AS job_seeker,
       v.title                AS vacancy,
       e.company_name         AS employer,
       c.contract_number,
       c.file_path            AS contract_file
FROM deals d
JOIN deal_statuses ds        ON ds.deal_status_id = d.deal_status_id
JOIN agents ag               ON ag.agent_id = d.agent_id
JOIN applications a          ON a.application_id = d.application_id
JOIN resumes r               ON r.resume_id = a.resume_id
JOIN job_seekers js          ON js.job_seeker_id = r.job_seeker_id
JOIN vacancies v             ON v.vacancy_id = a.vacancy_id
JOIN employers e             ON e.employer_id = v.employer_id
LEFT JOIN contracts c        ON c.deal_id = d.deal_id;

COMMENT ON VIEW v_deals_details IS 'Сделки с агентами, соискателями, вакансиями и договорами';

CREATE VIEW v_employment_statistics AS
SELECT es.name                          AS employment_status,
       count(DISTINCT js.job_seeker_id) AS job_seekers_count,
       round(avg(r.desired_salary), 2)  AS avg_desired_salary
FROM employment_statuses es
LEFT JOIN job_seekers js     ON js.employment_status_id = es.employment_status_id
LEFT JOIN resumes r          ON r.job_seeker_id = js.job_seeker_id AND r.is_active
GROUP BY es.employment_status_id, es.name
ORDER BY es.employment_status_id;

COMMENT ON VIEW v_employment_statistics IS 'Сводная статистика по статусам трудоустройства соискателей';

