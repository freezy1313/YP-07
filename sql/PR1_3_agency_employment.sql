    CONSTRAINT chk_reports_period CHECK (
        period_from IS NULL OR period_to IS NULL OR period_to >= period_from
    )
);

COMMENT ON TABLE  reports IS 'Сформированные отчёты и печатные формы';
COMMENT ON COLUMN reports.parameters IS 'Параметры формирования отчёта в формате JSON';

CREATE TABLE audit_log (
    audit_log_id  bigint       GENERATED BY DEFAULT AS IDENTITY,
    user_id       integer,
    action        varchar(20)  NOT NULL,
    entity_type   varchar(50)  NOT NULL,
    entity_id     bigint,
    details       jsonb,
    ip_address    inet,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_audit_log PRIMARY KEY (audit_log_id),
    CONSTRAINT fk_audit_log_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT chk_audit_log_action CHECK (
        action IN ('INSERT', 'UPDATE', 'DELETE', 'LOGIN', 'LOGOUT', 'EXPORT')
    )
);

COMMENT ON TABLE  audit_log IS 'Журнал действий пользователей и изменения статусов объектов';
COMMENT ON COLUMN audit_log.details IS 'Детали операции в формате JSON (старое и новое значение)';

