--  Практическая работа № 1.3. Создание базы данных
--
--  СУБД: PostgreSQL 18
--  Скрипт создаёт базу данных, таблицы, связи, ограничения, индексы,
--  представления и заполняет справочники и основное хранилище первичными
--  данными. Пароли пользователей хранятся в виде хешей (pgcrypto, bcrypt).
