BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =============================================================================
--  1. АВТОРИЗАЦИЯ, РОЛИ И ПОЛЬЗОВАТЕЛИ
-- =============================================================================

CREATE TABLE roles (
    role_id      integer      GENERATED BY DEFAULT AS IDENTITY,
    name         varchar(50)  NOT NULL,
    description  text,
    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_name UNIQUE (name),
    CONSTRAINT chk_roles_name CHECK (length(trim(name)) > 0)
);

COMMENT ON TABLE  roles IS 'Роли пользователей системы';
COMMENT ON COLUMN roles.name IS 'Наименование роли';

CREATE TABLE authorizations (
    authorization_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    login             varchar(50)  NOT NULL,
    password_hash     text         NOT NULL,
    CONSTRAINT pk_authorizations PRIMARY KEY (authorization_id),
    CONSTRAINT uq_authorizations_login UNIQUE (login),
    CONSTRAINT chk_authorizations_login
        CHECK (login ~ '^[A-Za-z0-9_]{4,50}$'),
    CONSTRAINT chk_authorizations_password_hash
        CHECK (length(password_hash) >= 20)
);

COMMENT ON TABLE  authorizations IS 'Учётные данные для входа в систему';
COMMENT ON COLUMN authorizations.login IS 'Уникальный логин пользователя';
COMMENT ON COLUMN authorizations.password_hash IS 'bcrypt-хеш пароля (pgcrypto, crypt/gen_salt)';

CREATE TABLE users (
    user_id           integer      GENERATED BY DEFAULT AS IDENTITY,
    role_id           integer      NOT NULL,
    last_name         varchar(100) NOT NULL,
    first_name        varchar(100) NOT NULL,
    middle_name       varchar(100),
    phone             varchar(20),
    email             varchar(254) NOT NULL,
    has_medical_book  boolean      NOT NULL DEFAULT false,
    authorization_id  integer      NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id)
        REFERENCES roles (role_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_users_authorization FOREIGN KEY (authorization_id)
        REFERENCES authorizations (authorization_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_users_authorization UNIQUE (authorization_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_last_name CHECK (length(trim(last_name)) > 0),
    CONSTRAINT chk_users_first_name CHECK (length(trim(first_name)) > 0),
    CONSTRAINT chk_users_email
        CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT chk_users_phone
        CHECK (phone IS NULL OR phone ~ '^\+?[0-9]{10,15}$')
);

COMMENT ON TABLE  users IS 'Пользователи: соискатели, работодатели и администраторы';
COMMENT ON COLUMN users.has_medical_book IS 'Наличие медицинской книжки';
COMMENT ON COLUMN users.authorization_id IS 'Ссылка на учётные данные (связь 1:1)';

-- =============================================================================
--  2. СОИСКАТЕЛИ, РЕЗЮМЕ И ЖЕЛАЕМЫЕ ДОЛЖНОСТИ
-- =============================================================================

CREATE TABLE desired_positions (
    desired_position_id  integer       GENERATED BY DEFAULT AS IDENTITY,
    specialization       varchar(150)  NOT NULL,
    description          text,
    salary               numeric(12,2),
    CONSTRAINT pk_desired_positions PRIMARY KEY (desired_position_id),
    CONSTRAINT uq_desired_positions_specialization UNIQUE (specialization),
    CONSTRAINT chk_desired_positions_salary CHECK (salary IS NULL OR salary >= 0)
);

COMMENT ON TABLE  desired_positions IS 'Справочник желаемых должностей и специализаций';
COMMENT ON COLUMN desired_positions.salary IS 'Ожидаемая заработная плата, руб.';

CREATE TABLE resume_statuses (
    resume_status_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    name              varchar(50)  NOT NULL,
    CONSTRAINT pk_resume_statuses PRIMARY KEY (resume_status_id),
    CONSTRAINT uq_resume_statuses_name UNIQUE (name),
    CONSTRAINT chk_resume_statuses_name CHECK (length(trim(name)) > 0)
);

COMMENT ON TABLE resume_statuses IS 'Справочник статусов резюме';

CREATE TABLE resumes (
    resume_id            integer  GENERATED BY DEFAULT AS IDENTITY,
    user_id              integer  NOT NULL,
    desired_position_id  integer  NOT NULL,
    experience           text,
    resume_status_id     integer  NOT NULL,
    personal_data_consent boolean NOT NULL DEFAULT false,
    published_at         date     NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_resumes PRIMARY KEY (resume_id),
    CONSTRAINT fk_resumes_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_resumes_desired_position FOREIGN KEY (desired_position_id)
        REFERENCES desired_positions (desired_position_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_resumes_status FOREIGN KEY (resume_status_id)
        REFERENCES resume_statuses (resume_status_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

COMMENT ON TABLE  resumes IS 'Резюме соискателей';
COMMENT ON COLUMN resumes.experience IS 'Описание опыта работы';
COMMENT ON COLUMN resumes.personal_data_consent IS 'Согласие на обработку персональных данных';

-- =============================================================================
--  3. РАБОТОДАТЕЛИ, ВАКАНСИИ И СПРАВОЧНИКИ
-- =============================================================================

CREATE TABLE employment_types (
    employment_type_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    name                varchar(80)  NOT NULL,
    CONSTRAINT pk_employment_types PRIMARY KEY (employment_type_id),
    CONSTRAINT uq_employment_types_name UNIQUE (name),
    CONSTRAINT chk_employment_types_name CHECK (length(trim(name)) > 0)
);

COMMENT ON TABLE employment_types IS 'Справочник типов занятости';

CREATE TABLE work_modes (
    work_mode_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    name          varchar(80)  NOT NULL,
    CONSTRAINT pk_work_modes PRIMARY KEY (work_mode_id),
    CONSTRAINT uq_work_modes_name UNIQUE (name),
    CONSTRAINT chk_work_modes_name CHECK (length(trim(name)) > 0)
);

COMMENT ON TABLE work_modes IS 'Справочник принципов работы (офис, удалённо, гибрид)';

CREATE TABLE position_titles (
    position_title_id  integer       GENERATED BY DEFAULT AS IDENTITY,
    name               varchar(150)  NOT NULL,
    CONSTRAINT pk_position_titles PRIMARY KEY (position_title_id),
    CONSTRAINT uq_position_titles_name UNIQUE (name),
    CONSTRAINT chk_position_titles_name CHECK (length(trim(name)) > 0)
);

COMMENT ON TABLE position_titles IS 'Справочник названий позиций';

CREATE TABLE vacancies (
    vacancy_id          integer       GENERATED BY DEFAULT AS IDENTITY,
    user_id             integer       NOT NULL,
    salary              numeric(12,2) NOT NULL,
    employment_type_id  integer       NOT NULL,
    work_mode_id        integer       NOT NULL,
    position_title_id   integer       NOT NULL,
    opened_at           date          NOT NULL DEFAULT CURRENT_DATE,
    closed_at           date,
    CONSTRAINT pk_vacancies PRIMARY KEY (vacancy_id),
    CONSTRAINT fk_vacancies_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_vacancies_employment_type FOREIGN KEY (employment_type_id)
        REFERENCES employment_types (employment_type_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_vacancies_work_mode FOREIGN KEY (work_mode_id)
        REFERENCES work_modes (work_mode_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_vacancies_position_title FOREIGN KEY (position_title_id)
        REFERENCES position_titles (position_title_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_vacancies_salary CHECK (salary >= 0),
    CONSTRAINT chk_vacancies_dates CHECK (closed_at IS NULL OR closed_at >= opened_at)
);

COMMENT ON TABLE  vacancies IS 'Вакансии, размещённые работодателями';
COMMENT ON COLUMN vacancies.user_id IS 'Работодатель — пользователь, разместивший вакансию';
COMMENT ON COLUMN vacancies.closed_at IS 'Дата закрытия вакансии; NULL — вакансия открыта';

-- =============================================================================
--  4. ОТКЛИКИ И СТАТУСЫ
-- =============================================================================

CREATE TABLE application_statuses (
    application_status_id  integer      GENERATED BY DEFAULT AS IDENTITY,
    name                   varchar(80)  NOT NULL,
    CONSTRAINT pk_application_statuses PRIMARY KEY (application_status_id),
    CONSTRAINT uq_application_statuses_name UNIQUE (name),
    CONSTRAINT chk_application_statuses_name CHECK (length(trim(name)) > 0)
);

COMMENT ON TABLE application_statuses IS 'Справочник статусов отклика на вакансию';

CREATE TABLE applications (
    application_id         integer  GENERATED BY DEFAULT AS IDENTITY,
    resume_id              integer  NOT NULL,
    vacancy_id             integer  NOT NULL,
    response_date          date     NOT NULL DEFAULT CURRENT_DATE,
    application_status_id  integer  NOT NULL,
    CONSTRAINT pk_applications PRIMARY KEY (application_id),
    CONSTRAINT fk_applications_resume FOREIGN KEY (resume_id)
        REFERENCES resumes (resume_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_applications_vacancy FOREIGN KEY (vacancy_id)
        REFERENCES vacancies (vacancy_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_applications_status FOREIGN KEY (application_status_id)
        REFERENCES application_statuses (application_status_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_applications_resume_vacancy UNIQUE (resume_id, vacancy_id)
);

COMMENT ON TABLE  applications IS 'Отклики соискателей на вакансии';
COMMENT ON COLUMN applications.response_date IS 'Дата отклика';

